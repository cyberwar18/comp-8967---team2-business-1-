const MONTHS: Record<string, string> = {
  Jan: 'janv.', Feb: 'févr.', Mar: 'mars', Apr: 'avr.', May: 'mai', Jun: 'juin', Jul: 'juil.', Aug: 'août', Sep: 'sept.', Oct: 'oct.', Nov: 'nov.', Dec: 'déc.',
  January: 'janvier', February: 'février', March: 'mars', April: 'avril', June: 'juin', July: 'juillet', August: 'août', September: 'septembre', October: 'octobre', November: 'novembre', December: 'décembre',
};
const DAYS: Record<string, string> = { Mon: 'lun.', Tue: 'mar.', Wed: 'mer.', Thu: 'jeu.', Fri: 'ven.', Sat: 'sam.', Sun: 'dim.' };
const MON = '(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)';

const hour = (h: string, m: string | undefined, ap: string) => {
  let n = Number(h) % 12;
  if (/p/i.test(ap)) n += 12;
  return m && m !== '00' ? `${n} h ${m}` : `${n} h`;
};

/** Dates and times: "Sat, Dec 5 · 1:00 PM" → "sam. 5 déc. · 13 h". */
export function frenchDates(s: string): string {
  return s
    .replace(new RegExp(`\\b(Mon|Tue|Wed|Thu|Fri|Sat|Sun), ${MON} (\\d{1,2})\\b`, 'g'), (_, d, m, n) => `${DAYS[d]} ${n} ${MONTHS[m]}`)
    .replace(new RegExp(`\\b${MON} (\\d{1,2})\\b`, 'g'), (_, m, n) => `${n} ${MONTHS[m]}`)
    .replace(/\b(January|February|March|April|June|July|August|September|October|November|December) (\d{4})\b/g, (_, m, y) => `${MONTHS[m]} ${y}`)
    .replace(/\b(\d{1,2}):(\d{2}) ?(AM|PM|am|pm)\b/g, (_, h, m, ap) => hour(h, m, ap))
    .replace(/\b(\d{1,2}) ?(am|pm)\b/g, (_, h, ap) => hour(h, undefined, ap));
}

