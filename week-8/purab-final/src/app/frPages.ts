function phrases(s: string): string {
  let out = s;
  for (const [en, fr] of PHRASES) if (out.includes(en)) out = out.split(en).join(fr);
  return out;
}

/** French for one piece of text, or null to leave it as it is. Spaces around it are kept. */
export function toFrench(text: string): string | null {
  const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(text)!;
  const core = m[2];
  if (!core || !/[A-Za-z]/.test(core)) return null;
  let out: string | undefined = FR_EXACT[core];
  if (out === undefined) {
    for (const [re, fn] of RULES) {
      const r = re.exec(core);
      if (r) {
        out = fn(...r);
        break;
      }
    }
  }
  const dated = phrases(frenchDates(out ?? core))
    .replace(/(\d h(?: \d+)?) to (\d+ h)/g, '$1 à $2')
    .replace(/\.\./g, '.');
  if (out === undefined && dated === core) return null;
  return m[1] + dated + m[3];
}
